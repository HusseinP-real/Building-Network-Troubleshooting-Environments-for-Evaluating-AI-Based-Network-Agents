"""Independent examples for the client-facing scoring and reporting contract.

Expected answers are literal fixtures, not copied from CASES or generated by the
scorer. No containers, credentials, model requests or historical results are used.
"""

import copy
import json
import sys
import tempfile
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "tools"))
import sade_benchmark as bench
import sade_eval as ev

UPLINK = {
    "is_anomaly": True,
    "resource_id": "interface/r5/eth0",
    "fault_type": "interface_down",
    "faulty_devices": ["r5"],
    "root_causes": [
        {
            "resource_id": "interface/r5/eth0",
            "fault_type": "interface_down",
            "device": "r5",
        }
    ],
    "repair_actions": [{"device": "r5", "command": "ip link set eth0 up"}],
    "diagnosis_text": "r5 eth0 is administratively down; redundant routing preserves application access.",
    "repair_text": "Restore r5 eth0.",
}
HEALTHY = {
    "is_anomaly": False,
    "resource_id": "none",
    "fault_type": "none",
    "faulty_devices": [],
    "root_causes": [],
    "repair_actions": [],
    "diagnosis_text": "Policy denial is expected and the network is healthy.",
    "repair_text": "No configuration change is needed.",
}
QUALITY = {
    "explanation_correct": True,
    "repair_correct": True,
    "explanation_reason": "Evidence supports the mechanism.",
    "repair_reason": "Targeted repair.",
}


class ScoringContractTests(unittest.TestCase):
    def test_independent_uplink_answer_receives_exact_credit(self):
        score = ev.score_prediction("core-uplink", UPLINK, QUALITY)
        for key in bench.AXES:
            self.assertIs(score[key], True, key)

    def test_wrong_interface_preserves_detection_but_loses_exact_credit(self):
        answer = copy.deepcopy(UPLINK)
        answer["resource_id"] = answer["root_causes"][0]["resource_id"] = (
            "interface/r5/eth1"
        )
        score = ev.score_prediction("core-uplink", answer, QUALITY)
        self.assertTrue(score["detection_correct"])
        self.assertTrue(score["device_correct"])
        self.assertFalse(score["localization_correct"])
        self.assertFalse(score["rca_exact"])
        self.assertFalse(score["full_correct"])

    def test_duplicate_root_causes_do_not_receive_exact_credit(self):
        answer = copy.deepcopy(UPLINK)
        answer["root_causes"] *= 2
        self.assertFalse(ev.score_prediction("core-uplink", answer)["rca_exact"])

    def test_healthy_control_and_false_positive_are_distinct(self):
        self.assertTrue(
            ev.score_prediction("healthy-policy", HEALTHY, QUALITY)["full_correct"]
        )
        self.assertFalse(
            ev.score_prediction("healthy-policy", UPLINK, QUALITY)["rca_exact"]
        )

    def test_scalar_fields_cannot_disagree_with_structured_causes(self):
        answer = copy.deepcopy(UPLINK)
        answer["fault_type"] = "vrrp_service_stopped"
        self.assertFalse(ev.score_prediction("core-uplink", answer)["rca_exact"])

    def test_missing_quality_is_unknown_not_a_pass(self):
        score = ev.score_prediction("core-uplink", UPLINK)
        self.assertTrue(score["rca_exact"])
        self.assertIsNone(score["explanation_correct"])
        self.assertIsNone(score["full_correct"])

    def test_malformed_structured_answer_is_rejected(self):
        prefix = (
            "=== DIAGNOSIS ===\nis_anomaly: true\nresource_id: interface/r5/eth0\n"
            "fault_type: interface_down\nfaulty_devices: r5\n"
        )
        for field in (
            "root_causes: {}",
            "root_causes: [null]",
            'root_causes: [{"device":"r5"}]',
            "repair_actions: {}",
            'repair_actions: [{"device":"r5","command":0}]',
        ):
            with self.subTest(field=field), self.assertRaises((ValueError, TypeError)):
                ev.parse_prediction(
                    prefix
                    + field
                    + "\ndiagnosis_text: Observed link failure.\n=== END ==="
                )


class SummaryContractTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.root = Path(self.tmp.name)

    def result(
        self, name, *, prediction=UPLINK, status="scored", model="fixed-test-model"
    ):
        path = self.root / (name + ".json")
        data = {
            "case": "core-uplink",
            "status": status,
            "model": model,
            "max_turns": 20,
            "scorer_version": ev.SCORER_VERSION,
            "benchmark_version": ev.BENCHMARK_VERSION,
            "mode": "live",
            "prompt_style": "generic",
            "tool_profile": "atomic",
            "state_verified": True,
            "repair_verified": True,
        }
        if status == "scored":
            data["score"] = ev.score_prediction("core-uplink", prediction, QUALITY)
        path.write_text(json.dumps(data))
        return path

    def test_empty_report_has_no_invented_accuracy(self):
        report = bench.summarize([])
        self.assertEqual(report["attempted"], 0)
        self.assertIsNone(report["metrics"]["rca_exact"]["rate"])
        self.assertIsNone(report["metrics"]["rca_exact"]["ci95"])
        self.assertEqual(report["suite_coverage"], 0)

    def test_model_mistake_is_scored_not_an_execution_error(self):
        wrong = copy.deepcopy(UPLINK)
        wrong["resource_id"] = "interface/r6/eth0"
        report = bench.summarize([self.result("wrong", prediction=wrong)])
        self.assertEqual(report["errors"], 0)
        self.assertEqual(report["complete_runs"], 1)
        self.assertEqual(report["metrics"]["rca_exact"]["rate"], 0)

    def test_all_attempts_including_errors_remain_in_accuracy_denominator(self):
        report = bench.summarize(
            [self.result("ok"), self.result("error", status="error")]
        )
        metric = report["metrics"]["rca_exact"]
        self.assertEqual((metric["correct"], metric["denominator"]), (1, 2))
        self.assertEqual(metric["rate"], 0.5)
        self.assertEqual(metric["rate_scored"], 1)
        self.assertEqual(report["errors"], 1)

    def test_same_result_file_cannot_be_counted_twice(self):
        path = self.result("single")
        report = bench.summarize([path, path, path.parent / "." / path.name])
        self.assertEqual(report["attempted"], 1)

    def test_summary_preserves_separate_model_configurations(self):
        report = bench.summarize(
            [self.result("a", model="A"), self.result("b", model="B")]
        )
        self.assertEqual(len(report["by_configuration"]), 2)
        self.assertTrue(
            all(
                group["attempted"] == 1 for group in report["by_configuration"].values()
            )
        )

    def test_accuracy_is_not_clamped_to_client_difficulty_target(self):
        for correct in (0, 3, 5):
            paths = [
                self.result(
                    f"{correct}-{i}", prediction=UPLINK if i < correct else HEALTHY
                )
                for i in range(5)
            ]
            self.assertEqual(
                bench.summarize(paths)["metrics"]["rca_exact"]["rate"], correct / 5
            )

    def test_manifest_faults_and_repair_plans_match_actual_devices(self):
        for case, metadata in ev.CASES.items():
            with self.subTest(case=case):
                self.assertEqual(
                    metadata["ground_truth"]["is_anomaly"], bool(ev.case_faults(case))
                )
                for fault in ev.case_faults(case):
                    self.assertIn(fault, ev.lab.FAULTS)
                    for phase in ("inject", "repair"):
                        node, command = ev.CASES[fault][phase + "_check"]
                        self.assertIn(node, ev.INVENTORY["nodes"])
                        self.assertTrue(command.strip())
                for repair in metadata["ground_truth"]["remediation"]:
                    self.assertIn(repair["device"], ev.INVENTORY["nodes"])


if __name__ == "__main__":
    unittest.main()
